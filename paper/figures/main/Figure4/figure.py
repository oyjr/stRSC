def t3_style_axis(ax, *, labelleft=True, labelbottom=True):
    ax.set_facecolor(T3_WHITE)
    for spine in ax.spines.values():
        spine.set_visible(True)  # L1 preserved: Nature-family thin four-sided frames.
        spine.set_color(T3_SPINE)
        spine.set_linewidth(0.55)
        spine.set_zorder(3)
    ax.grid(False)
    ax.set_axisbelow(True)
    ax.tick_params(
        axis="both", which="major", direction="out", length=2.1, width=0.5,
        color=T3_SPINE, labelcolor=T3_TEXT, labelsize=7.0, pad=2.0,
        labelleft=labelleft, labelbottom=labelbottom,
    )
    ax.tick_params(axis="both", which="minor", length=0)
    for tick in ax.get_xticklabels() + ax.get_yticklabels():
        tick.set_zorder(10)
    ax.xaxis.label.set_zorder(10)
    ax.yaxis.label.set_zorder(10)
    ax.title.set_zorder(10)


def t3_section(fig, bbox, letter, title, *, emphasis=False, offset=0.008):
    y = bbox.y1 + offset
    letter_artist = fig.text(
        0.018, y, letter, fontsize=10.0, fontweight="bold",
        color=T3_TEXT, va="bottom", ha="left", zorder=14,
    )
    title_artist = fig.text(
        bbox.x0, y, title, fontsize=8.3 if emphasis else 8.0,
        fontweight="regular",
        color=T3_TEXT, va="bottom", ha="left", zorder=14,
    )
    return letter_artist, title_artist


