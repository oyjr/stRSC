def t3_draw_mean_ci(ax, xpos, model, band, column, preserved_mean):
    row = t3_ci_lookup[(model, band, column)]
    estimate, low, high = (float(row[k]) for k in ("estimate", "lower", "upper"))
    assert np.isclose(preserved_mean, estimate, atol=1e-14, rtol=0)
    bars = ax.errorbar(xpos, estimate, yerr=[[estimate-low], [high-estimate]],
                      fmt="none", ecolor=T3_LIGHT, elinewidth=0.9,
                      capsize=1.8, capthick=0.9, zorder=1)
    t3_ci_records.append((ax, row, bars[2][0]))


